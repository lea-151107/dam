//go:build ignore

// gen_width generates widthtable.go from golang.org/x/text/width (the
// Unicode East Asian Width property). x/text is only used here, at
// generation time, so the library itself depends on the standard library.
//
// Run with: go run gen_width.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"

	"golang.org/x/text/width"
)

func main() {
	type rng struct{ lo, hi rune }
	var wide []rng
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		k := width.LookupRune(r).Kind()
		if k != width.EastAsianWide && k != width.EastAsianFullwidth {
			continue
		}
		if n := len(wide); n > 0 && wide[n-1].hi == r-1 {
			wide[n-1].hi = r
		} else {
			wide = append(wide, rng{r, r})
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_width.go from golang.org/x/text/width (Unicode %s); DO NOT EDIT.\n\n", width.UnicodeVersion)
	b.WriteString("package textgrid\n\n")
	b.WriteString("// wideRanges lists the East Asian Wide and Fullwidth code points as\n// sorted, inclusive, non-overlapping ranges.\n")
	b.WriteString("var wideRanges = [...][2]rune{\n")
	for _, w := range wide {
		fmt.Fprintf(&b, "\t{0x%04x, 0x%04x},\n", w.lo, w.hi)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("widthtable.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
